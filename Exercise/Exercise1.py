import math

# Square root of 144
print("Square root of 144 is:", math.sqrt(144))

# Factorial of  2^5 
print("Factorial of 2^5 is:", math.pow(2, 5))

# ceiling of 4.3
print("Ceiling of 4.3 is:", math.ceil(4.3))

# floor of 4.9
print("Floor of 4.9 is:", math.floor(4.9))

# value of pi
print("Value of pi is:", math.pi)
