# # List to Tuple
# l = [4, 5, 6]
# t = tuple(l)


t = (1, 2, 3)

l = list(t)   # convert in to list 
l.append(4)   # appned (add the element at end of all)

t = tuple(l)
print(t)   # (1, 2, 3, 4)  # we convert list to tuple 



